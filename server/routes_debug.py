# Debug device mode routes.
#
# Two of these are device-facing and both are locked:
#   POST /api/debug/enroll   needs an OTP the operator generated on the dashboard
#   POST /api/debug/upload   needs the token that enroll handed out
# Everything else is dashboard-session only.
#
# Split from routes_admin.py on purpose: this is the only place a device can
# push data the lyrics pipeline never sees, and keeping it in its own module is
# what makes that auditable.
import json
import os
import re
import threading
import time
from datetime import datetime
from urllib.parse import urlsplit

from collections import deque

from flask import request, jsonify

from .app import app, login_required, LOG_DIR, _sse_broadcast, SERVER_LOG_FILE, CRASH_LOG_FILE
from . import debug_mode

# Enroll is the one route a stranger can reach, and the only thing standing
# between them and a token is a 6-digit code. Ten tries per IP per five minutes
# makes guessing one impractical while never getting in the operator's way.
_ENROLL_WINDOW = 300
_ENROLL_MAX = 10
_attempts = {}
_attempts_lock = threading.Lock()

_RECORD_MAX = 200       # per upload
_URL_MAX = 900          # a videoplayback URL is long; it is the point of this
_BODY_MAX = 9000        # request body, already capped at 8KB by the device
_LINE_MAX = 900         # one app log line (the device caps at 700 chars)

_DEBUG_DIR = os.path.join(LOG_DIR, 'debug')
# A device id is generated by debug_mode ('dev' + 4 random bytes), so the shape
# is known and the file name never has to be trusted as a path component.
_DEVICE_RE = re.compile(r'^dev[0-9a-f]{8}$')
_TAIL_DEFAULT = 300
_TAIL_MAX = 2000


def _rate_limited(ip):
    now = time.time()
    with _attempts_lock:
        hits = [t for t in _attempts.get(ip, []) if now - t < _ENROLL_WINDOW]
        hits.append(now)
        _attempts[ip] = hits
        if len(_attempts) > 512:      # keep the table bounded on a busy host
            for key in [k for k, v in _attempts.items() if not v or now - v[-1] > _ENROLL_WINDOW]:
                _attempts.pop(key, None)
        return len(hits) > _ENROLL_MAX


def _txt(value, limit):
    if not isinstance(value, str):
        return ''
    cleaned = ''.join(ch if 32 <= ord(ch) < 127 or ord(ch) > 159 else ' ' for ch in value)
    return cleaned.strip()[:limit]


def _clean_record(raw, device_id):
    if not isinstance(raw, dict):
        return None
    url = _txt(raw.get('u'), _URL_MAX)
    if not url:
        return None
    host = path = ''
    try:
        parts = urlsplit(url)
        host = parts.hostname or ''
        path = (parts.path or '') + (('?' + parts.query[:300]) if parts.query else '')
    except Exception:
        pass
    record = {
        'ts': _txt(raw.get('t'), 40),
        'device': device_id,
        'm': _txt(raw.get('m'), 10) or 'GET',
        'host': host,
        'path': path,
        'vid': _txt(raw.get('vid'), 20),
        'u': url,
    }
    # A runtime probe ships a structured member dump (class names, ivar names
    # and value classes) instead of a request -- none of it is a URL, so none
    # of it fits the u/m/path columns; it rides the same envelope but keeps
    # its payload in `d`, bounded per item and per probe.
    if raw.get('kind') == 'probe':
        payload = raw.get('d')
        if isinstance(payload, dict):
            clean = {}
            for key, value in list(payload.items())[:12]:
                if not isinstance(value, dict):
                    continue
                items = value.get('items') if isinstance(value, dict) else None
                if not isinstance(items, list):
                    continue
                names = [_txt(x, 220) for x in items[:120] if isinstance(x, str)]
                clean[_txt(key, 40)] = {
                    'cls': _txt(value.get('cls'), 120),
                    'items': names,
                }
            if clean:
                record['kind'] = 'probe'
                record['d'] = clean
    # The request BODY a paired device captured. This used to be dropped right
    # here: the device sent it, the dashboard knew how to render it, and the
    # record this function built kept only the URL -- so body capture never
    # reached a file at all. Owner-debug only, same as on the device.
    if raw.get('owner_debug'):
        record['owner_debug'] = True
    body = _txt(raw.get('body'), _BODY_MAX)
    if body:
        record['body'] = body
    # App log lines (NSLog / _os_log_impl, Source/DebugLogCapture.x). There is
    # no URL to split into host/path -- the text IS the record, and the
    # log:// source lands in host the same way a probe's does.
    if raw.get('kind') == 'log':
        text = _txt(raw.get('line'), _LINE_MAX)
        if text:
            record['kind'] = 'log'
            record['log'] = text
    return record


def _human(size):
    return f'{size/1024:.1f}KB' if size < 1024 * 1024 else f'{size/1024/1024:.1f}MB'


def _debug_path(device_id):
    if not _DEVICE_RE.match(device_id or ''):
        return None
    path = os.path.join(_DEBUG_DIR, f'{device_id}.ndjson')
    return path if os.path.isfile(path) else None


def _tail(path, limit):
    """Last `limit` records of a capture file, parsed. A half-written final
    line (the device was killed mid-flush) is skipped, not fatal."""
    try:
        with open(path, 'r', encoding='utf-8', errors='replace') as f:
            lines = f.readlines()[-limit:]
    except OSError:
        return []
    out = []
    for raw in lines:
        try:
            rec = json.loads(raw)
        except Exception:
            continue
        if isinstance(rec, dict):
            out.append(rec)
    return out


def _file_info(path, device_id):
    try:
        stat = os.stat(path)
        # Count what the viewer can actually show: a device killed mid-flush
        # leaves a truncated tail line, and counting it would promise a row that
        # is not there. Parsing costs one pass over a debug-sized file.
        records = 0
        with open(path, 'r', encoding='utf-8', errors='replace') as f:
            for line in f:
                try:
                    json.loads(line)
                except Exception:
                    continue
                records += 1
    except OSError:
        return None
    return {
        'device': device_id,
        'records': records,
        'bytes': stat.st_size,
        'size_human': _human(stat.st_size),
        'modified': datetime.fromtimestamp(stat.st_mtime).isoformat(timespec='seconds'),
    }


@app.route('/api/debug/enroll', methods=['POST'])
def debug_enroll():
    ip = (request.headers.get('CF-Connecting-IP')
          or request.headers.get('X-Forwarded-For')
          or request.remote_addr or '?')
    if _rate_limited(ip):
        print(f"[WARN] [DEBUG-ENROLL] rate limited ip={ip}")
        return jsonify({'ok': False, 'error': 'too many attempts, wait a few minutes'}), 429
    body = request.get_json(silent=True) or {}
    result = debug_mode.enroll(body.get('otp'), body)
    if not result.get('ok'):
        print(f"[WARN] [DEBUG-ENROLL] refused ip={ip}: {result.get('error')}")
        return jsonify(result), 403
    print(f"[OK] [DEBUG-ENROLL] {result['id']} enrolled ip={ip} "
          f"name={_txt(body.get('name'), 40) or '?'} build={_txt(body.get('build'), 40) or '?'}")
    return jsonify(result)


@app.route('/api/debug/upload', methods=['POST'])
def debug_upload():
    token = request.headers.get('X-YTMU-Debug-Token', '')
    body = request.get_json(silent=True) or {}
    records = body.get('records')
    if not isinstance(records, list):
        return jsonify({'ok': False, 'error': 'records must be a list'}), 400
    records = records[:_RECORD_MAX]
    device = debug_mode.verify(token, count=len(records))
    if not device:
        # 401 for "unknown device" so the tweak can drop its token and stop
        # retrying; a 403 would mean "known device, not allowed" and it does not
        # exist on this route yet.
        return jsonify({'ok': False, 'error': 'unknown or revoked token'}), 401

    device_id = device['id']
    folder = os.path.join(LOG_DIR, 'debug')
    os.makedirs(folder, exist_ok=True)
    path = os.path.join(folder, f'{device_id}.ndjson')
    kept = 0
    kept_records = []
    with open(path, 'a', encoding='utf-8') as f:
        for raw in records:
            line = _clean_record(raw, device_id)
            if not line:
                continue
            f.write(json.dumps(line, ensure_ascii=False) + '\n')
            kept += 1
            kept_records.append(line)
            if kept <= 20:
                print(f"[DEBUG-CAP] {device_id} {line['m']} {line['host']}{line['path'][:160]}")
    print(f"[OK] [DEBUG-CAP] {device_id} {kept}/{len(records)} record(s) -> {path}")
    # Live tail for the dashboard. It rides the ONE existing events stream: a
    # second EventSource per page would be a second connection to the same host
    # for data the same operator is already listening to.
    if kept_records:
        _sse_broadcast('debug_cap', {'device': device_id, 'records': kept_records})
    return jsonify({'ok': True, 'accepted': kept})


@app.route('/api/debug/fetch', methods=['GET'])
def debug_fetch():
    """The read half of the pairing channel. The enrolled token (the one already
    on the device, and copyable from the Debug page) fetches two things without
    a dashboard session: THIS device's capture records and the tail of the
    server (or crash) log. Read-only on purpose -- verify_read bumps no counter,
    so uploads stay measurable as uploads. Token goes in the X-YTMU-Debug-Token
    header, never in the query string: the access log prints URLs, and a token
    would end up in the same file this endpoint returns.
    GET /api/debug/fetch?kind=device&limit=200   (default; this device's records)
    GET /api/debug/fetch?kind=server&limit=300   (server.log tail)
    GET /api/debug/fetch?kind=crash&limit=100    (crash.log tail)
    """
    token = request.headers.get('X-YTMU-Debug-Token', '')
    device = debug_mode.verify_read(token)
    if not device:
        return jsonify({'ok': False, 'error': 'unknown or revoked token'}), 401
    try:
        limit = int(request.args.get('limit', _TAIL_DEFAULT))
    except (TypeError, ValueError):
        limit = _TAIL_DEFAULT
    limit = min(max(limit, 1), _TAIL_MAX)
    kind = request.args.get('kind', 'device')
    if kind == 'device':
        path = _debug_path(device['id'])
        records = _tail(path, limit) if path else []
        return jsonify({'ok': True, 'kind': kind, 'device': device['id'], 'records': records})
    if kind in ('server', 'crash'):
        path = SERVER_LOG_FILE if kind == 'server' else CRASH_LOG_FILE
        lines = []
        try:
            with open(path, 'r', encoding='utf-8', errors='replace') as f:
                for raw in deque(f, maxlen=limit):
                    lines.append(_txt(raw.rstrip('\n'), 600))
        except OSError:
            lines = []
        return jsonify({'ok': True, 'kind': kind, 'lines': lines})
    return jsonify({'ok': False, 'error': 'kind must be device, server or crash'}), 400


@app.route('/api/admin/debug/otp', methods=['POST'])
@login_required
def admin_debug_otp():
    otp = debug_mode.new_otp()
    print(f"[OK] [DEBUG-OTP] generated (expires in {otp['expires_in']}s)")
    return jsonify(otp)


@app.route('/api/admin/debug/devices', methods=['GET'])
@login_required
def admin_debug_devices():
    devices = debug_mode.list_devices()
    # Newest first: the one you just enrolled is the one you are looking at.
    devices.sort(key=lambda d: d.get('created_at') or '', reverse=True)
    return jsonify({'devices': devices, 'pending': debug_mode.pending_count()})


@app.route('/api/admin/debug/devices/<device_id>/revoke', methods=['POST'])
@login_required
def admin_debug_revoke(device_id):
    ok = debug_mode.revoke(device_id)
    if ok:
        print(f"[WARN] [DEBUG-TOKEN] {device_id} revoked")
    return jsonify({'ok': ok})


@app.route('/api/admin/debug/files', methods=['GET'])
@login_required
def admin_debug_files():
    """The capture files themselves: one NDJSON per device, newest first."""
    files = []
    try:
        names = os.listdir(_DEBUG_DIR)
    except OSError:
        names = []
    for name in names:
        if not name.endswith('.ndjson'):
            continue
        device_id = name[:-len('.ndjson')]
        if not _DEVICE_RE.match(device_id):
            continue
        info = _file_info(os.path.join(_DEBUG_DIR, name), device_id)
        if info:
            files.append(info)
    files.sort(key=lambda f: f['modified'], reverse=True)
    return jsonify({'files': files})


@app.route('/api/admin/debug/files/<device_id>', methods=['GET'])
@login_required
def admin_debug_file(device_id):
    path = _debug_path(device_id)
    if not path:
        return jsonify({'ok': False, 'error': 'no such capture file'}), 404
    try:
        limit = int(request.args.get('limit', _TAIL_DEFAULT))
    except (TypeError, ValueError):
        limit = _TAIL_DEFAULT
    limit = min(max(limit, 1), _TAIL_MAX)
    records = _tail(path, limit)
    return jsonify({'ok': True, 'device': device_id, 'records': records})


@app.route('/api/admin/debug/files/<device_id>/download', methods=['GET'])
@login_required
def admin_debug_file_download(device_id):
    """The FULL capture file, untruncated (the view route caps at _TAIL_MAX).
    device_id is regex-validated by _debug_path, so the join cannot escape
    the capture directory."""
    path = _debug_path(device_id)
    if not path:
        return jsonify({'ok': False, 'error': 'no such capture file'}), 404
    from flask import send_file
    return send_file(path, as_attachment=True,
                     download_name=f'ytmu-capture-{device_id}.ndjson')


@app.route('/api/admin/debug/recent', methods=['GET'])
@login_required
def admin_debug_recent():
    """Seed for the live panel: what the capture already holds, so the page is
    not empty until the next flush. Files are read oldest-first and merged by
    append order per device -- the device stamps `t` itself and its clock is
    not ours, so do not pretend the merge is a sort."""
    try:
        limit = int(request.args.get('limit', 80))
    except (TypeError, ValueError):
        limit = 80
    limit = min(max(limit, 1), _TAIL_MAX)
    paths = []
    try:
        for name in os.listdir(_DEBUG_DIR):
            if not name.endswith('.ndjson'):
                continue
            if not _DEVICE_RE.match(name[:-len('.ndjson')]):
                continue
            path = os.path.join(_DEBUG_DIR, name)
            try:
                paths.append((os.path.getmtime(path), path))
            except OSError:
                pass
    except OSError:
        pass
    records = []
    for _, path in sorted(paths):
        records.extend(_tail(path, limit))
    return jsonify({'ok': True, 'records': records[-limit:]})
